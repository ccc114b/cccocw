def reflect(fragment):
    """處理代詞的轉換（例如：我 變成 你）"""
    # 依詞長由長到短排序，避免短詞搶先替換
    sorted_keys = sorted(reflections.keys(), key=len, reverse=True)
    placeholders = {}
    result = fragment

    for i, key in enumerate(sorted_keys):
        placeholder = f"\x00{i}\x00"
        if key in result:
            result = result.replace(key, placeholder)
            placeholders[placeholder] = reflections[key]

    for placeholder, value in placeholders.items():
        result = result.replace(placeholder, value)

    return result

def analyze(statement):
    """分析使用者的輸入並回傳 ELIZA 的回應"""
    # 去掉句尾的標點符號再進行比對（問句規則保留原始輸入以供比對）
    cleaned = re.sub(r'[。！？!?.]+$', '', statement.strip())
    
    for pattern, responses in psychobabble:
        # 若規則包含問號，則對原始輸入比對（保留全形問號）
        src = statement.strip() if '[?？]' in pattern else cleaned
        match = re.match(pattern, src)
        if match:
            response = random.choice(responses)
            if '{0}' in response:
                try:
                    captured = match.group(1)
                    return response.format(reflect(captured))
                except IndexError:
                    return response
            else:
                return response
    return "我不太明白你的意思，能再說清楚一點嗎？"

